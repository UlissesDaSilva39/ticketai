const fs = require("fs");
const content = [
'"use client";',
'',
'import { useState } from "react";',
'',
'export default function ShareButtonMini({ url, title }: { url: string; title: string }) {',
'  const [state, setState] = useState<"idle" | "copied">("idle");',
'',
'  const share = async (e: React.MouseEvent) => {',
'    e.preventDefault();',
'    e.stopPropagation();',
'    try {',
'      const nav = navigator as Navigator & { share?: (d: { title: string; url: string }) => Promise<void> };',
'      if (nav.share) {',
'        await nav.share({ title, url });',
'        return;',
'      }',
'      await navigator.clipboard.writeText(url);',
'      setState("copied");',
'      setTimeout(() => setState("idle"), 1500);',
'    } catch {}',
'  };',
'',
'  return (',
'    <button',
'      type="button"',
'      onClick={share}',
'      title={state === "copied" ? "Copied" : "Share"}',
'      className="w-8 h-8 rounded-full border border-gray-300 text-gray-600 hover:border-black hover:text-black flex items-center justify-center"',
'    >',
'      <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">',
'        <circle cx="18" cy="5" r="3" />',
'        <circle cx="6" cy="12" r="3" />',
'        <circle cx="18" cy="19" r="3" />',
'        <line x1="8.59" y1="13.51" x2="15.42" y2="17.49" />',
'        <line x1="15.41" y1="6.51" x2="8.59" y2="10.49" />',
'      </svg>',
'    </button>',
'  );',
'}',
].join("\n");
fs.writeFileSync("components/ShareButtonMini.tsx", content);
