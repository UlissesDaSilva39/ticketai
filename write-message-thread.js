const fs = require("fs");
const content = [
'"use client";',
'',
'import { useState, useRef, useEffect } from "react";',
'',
'type Msg = { id: string; sender_id: string; body: string; created_at: string };',
'',
'function timeOf(iso: string) {',
'  return new Date(iso).toLocaleTimeString("en-GB", { hour: "2-digit", minute: "2-digit" });',
'}',
'',
'export default function MessageThread({',
'  conversationId,',
'  currentUserId,',
'  initialMessages,',
'}: {',
'  conversationId: string;',
'  currentUserId: string;',
'  initialMessages: Msg[];',
'}) {',
'  const [messages, setMessages] = useState<Msg[]>(initialMessages);',
'  const [body, setBody] = useState("");',
'  const [busy, setBusy] = useState(false);',
'  const [error, setError] = useState<string | null>(null);',
'  const bottomRef = useRef<HTMLDivElement>(null);',
'',
'  useEffect(() => {',
'    bottomRef.current?.scrollIntoView({ behavior: "smooth" });',
'  }, [messages.length]);',
'',
'  const send = async (e: React.FormEvent) => {',
'    e.preventDefault();',
'    if (!body.trim() || busy) return;',
'    setBusy(true);',
'    setError(null);',
'',
'    const tempId = "temp-" + Date.now();',
'    const optimistic: Msg = {',
'      id: tempId,',
'      sender_id: currentUserId,',
'      body: body.trim(),',
'      created_at: new Date().toISOString(),',
'    };',
'    setMessages((m) => [...m, optimistic]);',
'    const text = body.trim();',
'    setBody("");',
'',
'    try {',
'      const res = await fetch("/api/messages/send", {',
'        method: "POST",',
'        headers: { "Content-Type": "application/json" },',
'        body: JSON.stringify({ conversationId, body: text }),',
'      });',
'      const data = await res.json();',
'      if (data.message) {',
'        setMessages((m) => m.map((x) => (x.id === tempId ? data.message : x)));',
'      } else {',
'        setMessages((m) => m.filter((x) => x.id !== tempId));',
'        setError(data.error || "Failed to send");',
'      }',
'    } catch (err) {',
'      setMessages((m) => m.filter((x) => x.id !== tempId));',
'      setError(err instanceof Error ? err.message : "Failed");',
'    } finally {',
'      setBusy(false);',
'    }',
'  };',
'',
'  return (',
'    <div className="flex flex-col border border-gray-200 rounded-2xl overflow-hidden">',
'      <div className="flex-1 p-4 space-y-3 min-h-[400px] max-h-[60vh] overflow-y-auto bg-gray-50">',
'        {messages.length === 0 && (',
'          <p className="text-center text-sm text-gray-500 py-8">No messages yet. Say hi.</p>',
'        )}',
'        {messages.map((m) => {',
'          const isMine = m.sender_id === currentUserId;',
'          return (',
'            <div key={m.id} className={"flex " + (isMine ? "justify-end" : "justify-start")}>',
'              <div',
'                className={',
'                  "max-w-[75%] px-4 py-2 rounded-2xl text-sm " +',
'                  (isMine ? "bg-black text-white rounded-br-sm" : "bg-white border border-gray-200 rounded-bl-sm")',
'                }',
'              >',
'                <p className="whitespace-pre-wrap break-words">{m.body}</p>',
'                <p className={"text-[10px] mt-1 " + (isMine ? "text-white/50" : "text-gray-400")}>',
'                  {timeOf(m.created_at)}',
'                </p>',
'              </div>',
'            </div>',
'          );',
'        })}',
'        <div ref={bottomRef} />',
'      </div>',
'',
'      <form onSubmit={send} className="border-t border-gray-200 bg-white p-3 flex gap-2">',
'        <input',
'          value={body}',
'          onChange={(e) => setBody(e.target.value)}',
'          placeholder="Write a message..."',
'          className="flex-1 px-4 py-2 border border-gray-300 rounded-full outline-none focus:border-black"',
'          disabled={busy}',
'        />',
'        <button',
'          type="submit"',
'          disabled={busy || !body.trim()}',
'          className="px-5 py-2 bg-black text-white rounded-full text-sm font-medium hover:bg-gray-800 disabled:opacity-50"',
'        >',
'          Send',
'        </button>',
'      </form>',
'      {error && <p className="text-xs text-red-600 px-4 pb-2">{error}</p>}',
'    </div>',
'  );',
'}',
].join("\n");
fs.writeFileSync("components/MessageThread.tsx", content);
console.log("components/MessageThread.tsx written:", content.length, "chars");